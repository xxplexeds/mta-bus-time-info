def _expand(spec):
    numbers = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            start, end = part.split("-")
            numbers.update(range(int(start), int(end) + 1))
        else:
            numbers.add(int(part))
    return numbers


_owners = {}
for _key, _depot in DEPOTS.items():
    for _n in _expand(_depot["buses"]):
        _owners.setdefault(_n, []).append(_key)

BY_NUMBER = {n: keys[0] for n, keys in _owners.items() if len(keys) == 1}
CONFLICTS = {n: keys for n, keys in _owners.items() if len(keys) > 1}

_NYCT_REF = re.compile(r"^MTA[ _]NYCT_(\d+)$", re.IGNORECASE)


def fleet_number(vehicle_ref):
    """'MTA NYCT_8445' -> 8445; anything else (MTABC_..., empty) -> None."""
    match = _NYCT_REF.match(str(vehicle_ref or "").strip())
    return int(match.group(1)) if match else None


def depot_for(vehicle_ref):
    """Depot key for a vehicle ref, or None if unknown."""
    number = fleet_number(vehicle_ref)
    return BY_NUMBER.get(number) if number is not None else None


def depot_badge(vehicle_ref):
    """'🏢 Jamaica', or '' when the depot isn't known."""
    key = depot_for(vehicle_ref)
    if not key:
        return ""
    depot = DEPOTS[key]
    return f"{depot['emoji']} {depot['name']}"
